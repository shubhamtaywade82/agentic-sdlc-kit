// packages/cli/src/commands/install.ts
//
// `kit install [--profile minimal|full-sdlc|runtime] [--stack <stack>] [--dry-run] [--json]`.
// M15 CLI installer: writes configuration files, tracks ownership, supports
// dry-run preview and idempotent re-installation.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { resolveStackPack } from '@agentic-sdlc-kit/core';
import type { Command, CommandContext, CommandResult } from './types.js';
import type { OwnershipEntry } from '@agentic-sdlc-kit/contracts';

interface InstallOperation {
  path: string;
  kind: 'create' | 'skip-existing' | 'overwrite-approved';
  content: string;
  sha256: string;
}

const FILES_BY_PROFILE: Record<string, ReadonlyArray<{ path: string; content: string }>> = {
  minimal: [
    {
      path: '.ai-kit/project.yml',
      content: [
        '# Generated by kit install --profile minimal',
        '# Run `kit init` to populate this file with detected values.',
        'schemaVersion: 1',
        'name: ""',
        'stack: []',
        'commands: {}',
        '',
      ].join('\n'),
    },
  ],
  'full-sdlc': [
    {
      path: '.ai-kit/project.yml',
      content: [
        '# Generated by kit install --profile full-sdlc',
        '# Run `kit init` to populate this file with detected values.',
        'schemaVersion: 1',
        'name: ""',
        'stack: []',
        'commands: {}',
        '',
      ].join('\n'),
    },
    {
      path: 'docs/specifications/.gitkeep',
      content: '',
    },
    {
      path: 'docs/plans/.gitkeep',
      content: '',
    },
    {
      path: 'docs/architecture/adr/.gitkeep',
      content: '',
    },
    {
      path: 'docs/releases/.gitkeep',
      content: '',
    },
  ],
  runtime: [
    {
      path: '.ai-kit/state/.gitkeep',
      content: '',
    },
    {
      path: '.ai-kit/reports/.gitkeep',
      content: '',
    },
  ],
};

async function sha256(text: string): Promise<string> {
  const crypto = await import('node:crypto');
  return crypto.createHash('sha256').update(text, 'utf8').digest('hex');
}

async function fileExists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

export const installCommand: Command = {
  name: 'install',
  summary: 'Install and configure kit environment, instructions, and stack packs (M15).',
  async run(ctx: CommandContext): Promise<CommandResult> {
    if (ctx.argv.includes('--help') || ctx.argv.includes('-h')) {
      ctx.stdout(formatHelp());
      return { exitCode: 0 };
    }

    const isJson = ctx.argv.includes('--json');
    const isDryRun = ctx.argv.includes('--dry-run');
    const stackIdx = ctx.argv.indexOf('--stack');
    const stackName = stackIdx !== -1 ? ctx.argv[stackIdx + 1] : undefined;
    const profileIdx = ctx.argv.indexOf('--profile');
    const installProfile = profileIdx !== -1 ? ctx.argv[profileIdx + 1] : 'full-sdlc';

    if (!installProfile || !FILES_BY_PROFILE[installProfile]) {
      ctx.stderr(`kit install: unknown profile '${installProfile ?? '(missing)'}'\n`);
      return { exitCode: 1, message: `unknown profile: ${installProfile ?? '(missing)'}` };
    }

    // Plan: compute operations for the selected profile.
    const filesToWrite = FILES_BY_PROFILE[installProfile]!;
    const operations: InstallOperation[] = [];

    for (const file of filesToWrite) {
      const targetPath = path.join(ctx.cwd, file.path);
      const exists = await fileExists(targetPath);
      let kind: InstallOperation['kind'] = 'create';
      if (exists) {
        // Idempotent: skip files that already exist unless they're .gitkeep
        // (which are safe to overwrite).
        if (file.path.endsWith('.gitkeep')) {
          kind = 'overwrite-approved';
        } else {
          kind = 'skip-existing';
        }
      }
      const hash = await sha256(file.content);
      operations.push({ path: file.path, kind, content: file.content, sha256: hash });
    }

    // If a stack is specified, record it in the plan.
    let stackInfo = 'none';
    if (stackName) {
      const pack = resolveStackPack(stackName);
      stackInfo = pack ? pack.name : stackName;
    }

    // In dry-run mode, print the plan and exit without writing.
    if (isDryRun) {
      const plan = {
        profile: installProfile,
        stack: stackInfo,
        dryRun: true,
        operations: operations.map((op) => ({
          path: op.path,
          kind: op.kind,
          sha256: op.sha256,
        })),
      };
      if (isJson) {
        ctx.stdout(JSON.stringify(plan, null, 2) + '\n');
      } else {
        ctx.stdout(formatDryRun(plan));
      }
      return { exitCode: 0 };
    }

    // Execute: write files that are create or overwrite-approved.
    const writtenFiles: string[] = [];
    const skippedFiles: string[] = [];
    const ownershipEntries: OwnershipEntry[] = [];
    const now = new Date().toISOString();

    for (const op of operations) {
      if (op.kind === 'skip-existing') {
        skippedFiles.push(op.path);
        continue;
      }
      const targetPath = path.join(ctx.cwd, op.path);
      await fs.mkdir(path.dirname(targetPath), { recursive: true });
      await fs.writeFile(targetPath, op.content, 'utf8');
      writtenFiles.push(op.path);
      // By this point, the file was written (create or overwrite-approved);
      // preserved is false because we did not skip it.
      ownershipEntries.push({
        packageId: 'agentic-sdlc-kit',
        packageVersion: '0.7.1',
        path: op.path,
        sha256: op.sha256,
        installedAt: now,
        preserved: false,
      });
    }

    // Write ownership manifest so kit uninstall knows what we own.
    const manifestPath = path.join(ctx.cwd, '.ai-kit', 'ownership-manifest.json');
    await fs.mkdir(path.dirname(manifestPath), { recursive: true });
    const manifest = {
      schemaVersion: 1,
      root: ctx.cwd,
      scope: 'project',
      entries: ownershipEntries,
    };
    await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

    const result = {
      installed: true,
      profile: installProfile,
      stack: stackInfo,
      writtenFiles,
      skippedFiles,
      ownershipManifest: '.ai-kit/ownership-manifest.json',
    };

    if (isJson) {
      ctx.stdout(JSON.stringify(result, null, 2) + '\n');
    } else {
      ctx.stdout(formatResult(result));
    }

    return { exitCode: 0 };
  },
};

interface DryRunPlan {
  profile: string;
  stack: string;
  dryRun: boolean;
  operations: Array<{ path: string; kind: string; sha256: string }>;
}

function formatDryRun(plan: DryRunPlan): string {
  const lines: string[] = [
    'kit install --dry-run',
    `  Profile: ${plan.profile}`,
    `  Stack:   ${plan.stack}`,
    '',
    'Planned operations:',
  ];
  for (const op of plan.operations) {
    lines.push(`  ${op.kind.padEnd(20)} ${op.path}`);
  }
  lines.push('');
  lines.push(`${plan.operations.length} operation(s) planned. Run without --dry-run to execute.`);
  lines.push('');
  return lines.join('\n');
}

interface InstallResult {
  installed: boolean;
  profile: string;
  stack: string;
  writtenFiles: string[];
  skippedFiles: string[];
  ownershipManifest: string;
}

function formatResult(r: InstallResult): string {
  const lines: string[] = [
    'kit install: SUCCESS',
    `  Profile:      ${r.profile}`,
    `  Stack:        ${r.stack}`,
    `  Written:      ${r.writtenFiles.length} file(s)`,
  ];
  for (const f of r.writtenFiles) {
    lines.push(`    + ${f}`);
  }
  if (r.skippedFiles.length > 0) {
    lines.push(`  Skipped:      ${r.skippedFiles.length} existing file(s)`);
    for (const f of r.skippedFiles) {
      lines.push(`    ~ ${f}`);
    }
  }
  lines.push(`  Ownership:    ${r.ownershipManifest}`);
  lines.push('');
  return lines.join('\n');
}

function formatHelp(): string {
  return [
    'Usage: kit install [--profile <profile>] [--stack <stack>] [--dry-run] [--json]',
    '',
    'Install and configure kit environment, instructions, commands, and stack packs.',
    '',
    'Profiles:',
    '  minimal      Core instructions and essential skills only',
    '  full-sdlc    Complete workflows, agents, templates, and planning engines (default)',
    '  runtime      Runtime governance, secret protection, and model routing mods',
    '',
    'Options:',
    '  --stack <id> Stack pack to activate (e.g. node-typescript, ruby-rails)',
    '  --dry-run    Preview planned operations without writing files',
    '  --json       Output machine-readable installation status',
    '  --help       Show this message',
    '',
  ].join('\n');
}
